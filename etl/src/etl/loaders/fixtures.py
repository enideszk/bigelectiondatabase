"""Loader for the FAKE development fixture in data/fixtures/ (`etl seed fixtures`).

The fixture files are already "interim" files (clean CSVs whose headers match table columns),
so this loader only has a load step. It is also the smallest complete example of a loader:
register the source, insert everything in dependency order inside one transaction, refresh
the aggregates.
"""

from __future__ import annotations

from pathlib import Path

import psycopg

from .. import config, db
from ._common import SourceInfo, copy_csv, load_geojson_geometries, replace_source, reset_serial

SOURCE = SourceInfo(
    name="FAKE fixture data",
    publisher="hu-data-platform (generated by data/fixtures/make_fixtures.py)",
    file_name="data/fixtures/",
    notes="Invented development data. Not real places, parties or election results.",
)

# (csv file, table, carries source_id) in dependency order
TABLES = [
    ("units.csv", "unit", True),
    ("unit_names.csv", "unit_name", True),
    ("unit_parents.csv", "unit_parent", True),
    ("unit_lineage.csv", "unit_lineage", True),
    ("district_sets.csv", "district_set", True),
    ("elections.csv", "election", True),
    ("election_rounds.csv", "election_round", True),
    ("electoral_districts.csv", "electoral_district", True),
    ("district_memberships.csv", "district_membership", True),
    ("polling_stations.csv", "polling_station", True),
    ("parties.csv", "party", True),
    ("party_names.csv", "party_name", True),
    ("party_lists.csv", "party_list", True),
    ("party_list_members.csv", "party_list_member", False),
    ("candidates.csv", "candidate", True),
    ("candidate_parties.csv", "candidate_party", False),
    ("turnout.csv", "turnout", True),
    ("list_results.csv", "list_result", True),
    ("candidate_results.csv", "candidate_result", True),
    ("indicators.csv", "indicator", True),
    ("indicator_values.csv", "indicator_value", True),
]


class FixtureRefused(RuntimeError):
    pass


def run(conn: psycopg.Connection, fixtures_dir: Path = config.FIXTURES_DIR, force: bool = False) -> dict[str, int]:
    """Load (or reload) the fixture. Refuses if the database holds real sources, unless force."""
    others = conn.execute("SELECT name FROM source WHERE name <> %s", (SOURCE.name,)).fetchall()
    if others and not force:
        raise FixtureRefused(
            "The database already holds other sources "
            f"({', '.join(r[0] for r in others[:3])}...). Fake and real data must not be mixed; "
            "use a separate database or `etl db reset` first."
        )
    counts: dict[str, int] = {}
    with conn.transaction():
        source_id = replace_source(conn, SOURCE)
        for file_name, table, has_source in TABLES:
            counts[table] = copy_csv(conn, table, fixtures_dir / file_name, source_id if has_source else None)
        counts["unit_geometry"] = load_geojson_geometries(conn, fixtures_dir / "geometries.geojson", source_id)
        reset_serial(conn, "party_list", "list_id")
        reset_serial(conn, "candidate", "candidate_id")
    db.refresh_aggregates(conn)
    return counts
